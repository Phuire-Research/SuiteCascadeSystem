/**
 * Generates the CADMIUM-LIKENESS concept bundle for a validated NameDerivation. File paths are
 * relative to SCP/src/ — the consuming Clone + Rename Engine (M2-A1-D3) prepends the absolute SCP
 * install path at write time.
 *
 * C727 · 5 · the emit set grew 3 → 6 so a minted S8 page self-muxifies OUT OF THE BOX (r4 Chain B):
 *   1. <name>.type.ts          — the base type (Name + State + Qualities type)
 *   2. <name>.state.ts         — the base state factory (client-safe · reused by the client face)
 *   3. <name>.concept.ts       — the base concept (Huirth-capable · empty qualities)
 *   4. <name>.concept.client.ts — B1 · the DEDICATED client face (create<Pascal>ClientConcept)
 *   5. <name>.muxonomy.ts       — B2 · the muxonomy wrapper (<camel>Muxonomic)
 *   6. vue/<Pascal>Landing.vue  — B3 · the self-muxifying page (3-node createClientMuxiumInstance)
 * The client face reuses the base .state factory (pure defaults · no server deps) rather than
 * emitting a separate client-state file, so the delta is 6 files, not 7. B4 (route + nav) is the
 * mint-time registration step, not a src file (Stage 6).
 */
export function generateBareMinimumConcept(d: NameDerivation): GeneratedConceptBundle {
  const dir = `concepts/${d.conceptName}`;
  const files: GeneratedConceptFile[] = [
    {
      relativePath: `${dir}/${d.conceptName}.type.ts`,
      content: generateTypeFile(d),
    },
    {
      relativePath: `${dir}/${d.conceptName}.state.ts`,
      content: generateStateFile(d),
    },
    {
      relativePath: `${dir}/${d.conceptName}.concept.ts`,
      content: generateConceptFile(d),
    },
    // C727 · 5 · B1 · the dedicated client concept face (the muxifiable node).
    {
      relativePath: `${dir}/${d.conceptName}.concept.client.ts`,
      content: generateClientConceptFile(d),
    },
    // C727 · 5 · B2 · the muxonomy wrapper paired with the client concept.
    {
      relativePath: `${dir}/${d.conceptName}.muxonomy.ts`,
      content: generateMuxonomyFile(d),
    },
    // C727 · 5 · B3 · the self-muxifying Landing page (3-node createClientMuxiumInstance · GPIM).
    {
      relativePath: `${dir}/vue/${d.designation}Landing.vue`,
      content: generateLandingVue(d),
    },
  ];
  return {
    files,
    conceptName: d.conceptName,
    designation: d.designation,
    fileCount: files.length,
  };
}
