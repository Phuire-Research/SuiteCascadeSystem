import type { NameDerivation } from './designationValidator.model';

// ============================================
// GENERATED FILE BUNDLE
// ============================================

export interface GeneratedConceptFile {
  relativePath: string;    // relative to SCP/src/ (e.g. "concepts/myResearch/myResearch.type.ts")
  content: string;
}

export interface GeneratedConceptBundle {
  files: GeneratedConceptFile[];
  conceptName: string;
  designation: string;
  fileCount: number;
}

