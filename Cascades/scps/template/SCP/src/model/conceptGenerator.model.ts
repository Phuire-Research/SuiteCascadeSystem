/**
 * B1 · the dedicated CLIENT concept face. Mirrors cadmium.concept.client.ts — reuses the generated
 * base .type (Name + Qualities type) + .state factory (client-safe · pure defaults), seeds an empty
 * client qualities map (grow later), and exports create<Pascal>ClientConcept() as the muxifiable node.
 */
function generateClientConceptFile(d: NameDerivation): string {
  const PascalName = d.designation;
  const camelName = d.conceptName;
  return `/**
 * ${PascalName} Client Concept Factory
 *
 * The DEDICATED client face muxified into this designation's own Client Muxium by
 * ${PascalName}Landing.vue (the Cadmium likeness). Reuses the base .type + .state; seeds an
 * empty client qualities map — add Client qualities here as the page grows.
 *
 * Higher-Order Composition: this stands as a base concept; the Landing page muxifies it as a
 * MuxonomicConcept node (Tier 2 · d.client.d.${camelName}.k.property.select()). No 3rd tier.
 *
 * Citation: cadmium.concept.client.ts (the dedicated-concept-per-S8 likeness).
 * Citation: STRATIMUX-REFERENCE.md "🎯 Essential Principles for Successful StratiDECK".
 */
import { createConcept } from 'stratimux';
import { ${camelName}Name, type ${PascalName}Qualities } from './${camelName}.type';
import { create${PascalName}State } from './${camelName}.state';

// Explicit quality mapping — NEVER typeof. Empty at mint; add Client qualities as the page grows.
const ${camelName}ClientQualities: ${PascalName}Qualities = {};

export const create${PascalName}ClientConcept = () => {
  return createConcept(
    ${camelName}Name,
    create${PascalName}State(),
    ${camelName}ClientQualities,
    [],
  );
};
`;
}

/**
 * B2 · the muxonomy wrapper + navigation + creator. Mirrors cadmium.muxonomy.ts — the MuxonomicConfig
 * paired with the client concept in the createClientMuxiumInstance array, PLUS the two exports the
 * build-time muxonomy registry scan (generateMuxonomyRegistry · npm run strativerse:scan) requires to
 * AUTO-REGISTER the page's route + sidebar nav (B4 · the automatic `scs suite8:page`):
 *   - export const <camel>Muxonomic  (the config · the registry's configMatch)
 *   - export function createMuxonomic<Pascal>()  (the MuxonomicConcept creator · the registry's
 *     creatorMatch · feeds ISLAND_CREATORS)
 *   - a navigation:{ pages:[{ componentPath }] } block  (the registry's hasNavigation + island harvest
 *     → the /<camel> route resolving to <Pascal>Landing.vue)
 * Minimal otherwise — no Diametric routes yet (those travel WITH suiteCascade · Cadmium note).
 *
 * Citation: cadmium.muxonomy.ts (the dedicated-concept muxonomy wrapper + navigation).
 * Citation: generateMuxonomyRegistry.quality.huirth.diameter.ts (the scan contract · configMatch +
 *           creatorMatch + hasNavigation + componentPath island harvest).
 * Citation: muxonomy.model.ts MuxonomicConfig.
 */
function generateMuxonomyFile(d: NameDerivation): string {
  const PascalName = d.designation;
  const camelName = d.conceptName;
  return `/**
 * ${PascalName} Muxonomy Configuration
 *
 * The MuxonomicConfig wrapper paired with create${PascalName}ClientConcept() in the
 * createClientMuxiumInstance array on ${PascalName}Landing.vue, plus the navigation + creator exports
 * the build-time registry scan harvests to AUTO-REGISTER the /${camelName} route + sidebar nav.
 * Minimal at mint — the InductionState filterKeys only; add demometers / actionExchange routes as
 * Client qualities land.
 *
 * Citation: cadmium.muxonomy.ts (the dedicated-concept muxonomy wrapper + navigation).
 * Citation: muxonomy.model.ts MuxonomicConfig.
 */
import {
  type MuxonomicConfig,
  type MuxonomicConcept,
  type NavigationConfig,
  type PageEntry,
  ChangeDetectionMode,
} from '../muxonomy/muxonomy.model';
import { create${PascalName}ClientConcept } from './${camelName}.concept.client';

const ${camelName}LandingPage: PageEntry = {
  path: '/${camelName}',
  label: '${PascalName}',
  order: 0,
  componentPath: '${camelName}/vue/${PascalName}Landing',
  isMain: true,
};

// B4 · the sidebar nav entry. isMainLanding stays FALSE at mint — the DEFAULT Home owns the landing
// until a user domain page claims it (the FT-009 correction · matches cadmium.muxonomy.ts).
export const ${camelName}Navigation: NavigationConfig = {
  isMainLanding: false,
  icon: '🎯',
  color: 'base',
  label: '${PascalName}',
  order: 5,
  pages: [${camelName}LandingPage],
};

export const ${camelName}Muxonomic: MuxonomicConfig<'${camelName}'> = {
  conceptName: '${camelName}',
  filterKeys: ['actionQue', 'filterKeys'],
  novelChange: {
    mode: ChangeDetectionMode.KeyedSelector,
  },
  // Nothing synced at mint (a client-local page · no Diametric routes yet). Add filterKeys here as
  // Client qualities that must broadcast to Huirth land.
  sync: {
    direction: 'toClient',
    filterKeys: [],
    novelChange: {
      mode: ChangeDetectionMode.KeyedSelector,
    },
  },
  demometers: {
    qualities: [],
    strategies: [],
    principles: [],
  },
  decks: {
    huirth: '${PascalName}HuirthDeck',
    client: '${PascalName}ClientDeck',
  },
  navigation: ${camelName}Navigation,
};

// The MuxonomicConcept creator the registry scan harvests into ISLAND_CREATORS (the createMuxonomic
// export the scan's creatorMatch requires). Pairs the dedicated client concept with its config.
export function createMuxonomic${PascalName}(): MuxonomicConcept<'${camelName}'> {
  return {
    concept: create${PascalName}ClientConcept(),
    muxonomy: ${camelName}Muxonomic,
  };
}
`;
}

/**
 * B3 · the self-muxifying Landing page. Mirrors CadmiumLanding's GPIM block (r4:563-579) modeled on
 * the in-repo Suite8Landing.vue: a 3-node createClientMuxiumInstance (generic suite8 + dedicated +
 * suiteCascade prior base) + GPIM bind/unbind + <Suite8CascadeDocs :designation> rendering THIS
 * designation's live Diamond/Onyx from its own Working/ pair (the full round-trip payoff).
 */
function generateLandingVue(d: NameDerivation): string {
  const PascalName = d.designation;
  const camelName = d.conceptName;
  return `<script setup lang="ts">
/**
 * ${PascalName} Landing — the self-muxifying Suite 8 page (the Cadmium likeness).
 *
 * This page creates its OWN Client Muxium and muxifies THREE nodes:
 *   1. createSuite8ClientConcept()   — the generic suite8 face (roster + docked cascade context)
 *   2. create${PascalName}ClientConcept() — THIS designation's DEDICATED concept (Tier 2 ·
 *                                      d.client.d.${camelName}.k.property.select())
 *   3. createSuiteCascadeConcept()   — the PRIOR base (S8RI) carrying live Diamond/Onyx docs
 *
 * <Suite8CascadeDocs :designation> reads THIS designation's own Cascades/Extended/${PascalName}/
 * Working/ pair via the extended auto-registration circuit — the founding writes the pair into
 * Working/, this page renders it live, and a page edit saves back into Working/ (round-trip).
 *
 * Citation: CadmiumLanding.vue (the GPIM self-muxify block · r4 Chain B).
 * Citation: Suite8Landing.vue (the in-repo createClientMuxiumInstance + GPIM bind/unbind pattern).
 */
import { onMounted, onUnmounted } from 'vue';
import type { Muxium } from 'stratimux';
import { createClientMuxiumInstance, type ClientMuxiumDeck } from '../../client/client.muxonomy';
// Node 1 · the generic suite8 face.
import { createSuite8ClientConcept } from '../../suite8/suite8.concept.client';
import { suite8Muxonomic } from '../../suite8/suite8.muxonomy';
// Node 2 · THIS designation's dedicated concept.
import { create${PascalName}ClientConcept } from '../${camelName}.concept.client';
import { ${camelName}Muxonomic } from '../${camelName}.muxonomy';
// Node 3 · the suiteCascade prior base (S8RI · live Diamond/Onyx relay).
import { createSuiteCascadeConcept } from '../../suiteCascade/suiteCascade.concept.client';
import { suiteCascadeMuxonomic } from '../../suiteCascade/suiteCascade.muxonomy';
// GPIM · Vue-layer Muxium binding into the universal scsBridge controller.
import { getGlobalScsBridgeController } from '../../scsBridge/scsBridgeController';
// The per-designation cascade docs pane (path-agnostic · reads Working/ live).
import Suite8CascadeDocs from '../../suite8/vue/components/Suite8CascadeDocs.vue';

let muxium: Muxium<ClientMuxiumDeck> | null = null;

onMounted(() => {
  // The 3-node self-muxify — the Cadmium likeness out of the box.
  muxium = createClientMuxiumInstance<ClientMuxiumDeck>(
    [
      { concept: createSuite8ClientConcept(), muxonomy: suite8Muxonomic },
      { concept: create${PascalName}ClientConcept(), muxonomy: ${camelName}Muxonomic },
      { concept: createSuiteCascadeConcept(), muxonomy: suiteCascadeMuxonomic },
    ],
    {
      title: '${PascalName}Landing',
      logging: true,
      storeDialog: true,
    },
  );

  // GPIM · bind this landing's Muxium into the universal scsBridge controller.
  const sbController = getGlobalScsBridgeController();
  if (sbController) sbController.setMuxium(muxium);
});

onUnmounted(() => {
  // GPIM cleanup · unbind controller from this landing's Muxium (mirror CadmiumLanding).
  const sbController = getGlobalScsBridgeController();
  if (sbController) sbController.setMuxium(null);
  if (muxium) muxium.close();
});
</script>

<template>
  <div class="${camelName}-landing">
    <header class="landing-header">
      <h1 class="hifi-heading spectrum-text">${PascalName}</h1>
    </header>
    <Suite8CascadeDocs :designation="'${PascalName}'" />
  </div>
</template>
`;
}

